#!/usr/bin/env python3
"""Generate BVO-04 16-kHz stereo WAV fixtures and embedded read-only data.

Speech source: TensorFlow Lite Micro micro_speech yes_1000ms.wav, in the
existing apps checkout. Each signed mono sample is copied to L/R after
integer attenuation by 4. Tone: deterministic 1-kHz sine, peak 2047 (-24 dBFS).
"""
import hashlib
import io
import math
from pathlib import Path
import struct
import subprocess
import wave

root = Path(__file__).resolve().parents[1]
source = root.parent / 'apps/mlearning/tflite-micro/tflite-micro/tensorflow/lite/micro/examples/micro_speech/testdata/yes_1000ms.wav'
out = root / 'docs/voice-evidence/2026-10-21/bvo-04/fixtures'
out.mkdir(parents=True, exist_ok=True)
with wave.open(str(source), 'rb') as w:
    assert (w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()) == (1, 2, 16000, 16000)
    mono = struct.unpack('<16000h', w.readframes(16000))

def wav(samples):
    b = io.BytesIO()
    with wave.open(b, 'wb') as w:
        w.setparams((2, 2, 16000, 0, 'NONE', 'not compressed'))
        w.writeframes(b''.join(struct.pack('<hh', n, n) for n in samples))
    return b.getvalue()

tone = [round(2047 * math.sin(2 * math.pi * 1000 * i / 16000)) for i in range(16000)]
files = {'tone.wav': wav(tone), 'speech.wav': wav([int(n / 4) for n in mono])}
# Embed exact WAV bytes to avoid a separate host file-transfer service.
header = ['/* SPDX-License-Identifier: Apache-2.0 */',
          '/* Generated by scripts/gen_audio_fixtures.py; speech is from TFLM.',
          ' * TFLM sources are Apache-2.0; retain provenance in fixtures/README.md. */']
for name, data in files.items():
    (out / name).write_bytes(data)
    symbol = 'vg_audio_' + name.split('.')[0]
    header.append('static const unsigned char ' + symbol + '[] = {')
    for i in range(0, len(data), 20):
        header.append('  ' + ','.join('0x%02x' % b for b in data[i:i+20]) + ',')
    header.append('};')
(root / 'app/velaguard/vg_audio_fixtures.h').write_text('\n'.join(header) + '\n')
(out / 'SHA256SUMS').write_text(''.join(hashlib.sha256(v).hexdigest() + '  ' + k + '\n' for k,v in files.items()))
(out / 'README.md').write_text('''BVO-04 fixtures: WAV PCM signed 16-bit little endian, 16000 Hz, stereo L=R,
16000 frames / 64000 payload bytes / 64044 file bytes / 1 second each.
Tone: generated 1 kHz sine, peak 2047, -24.09 dBFS.
Speech: existing TFLM micro_speech/testdata/yes_1000ms.wav, mono samples divided
by four (truncated toward zero), duplicated into left and right channels.
Source WAV SHA256: ''' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
+ 'Source repository: https://github.com/tensorflow/tflite-micro (Apache-2.0).\n'
+ 'Actual local source checkout: ' + subprocess.check_output(['git', '-C', str(root.parent / 'apps/mlearning/tflite-micro/tflite-micro'), 'rev-parse', 'HEAD'], text=True).strip() + '\n'
+ 'Reproduce: python3 scripts/gen_audio_fixtures.py\n')
