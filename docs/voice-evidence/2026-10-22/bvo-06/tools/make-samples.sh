#!/usr/bin/env bash
# Build the BVO-06 test sample set.
#
# Speech is synthesized locally with the Windows SAPI zh-CN voice
# (Microsoft Huihui) at 16000 Hz / 16-bit / mono, then padded with silence to
# an exact duration. Speech is never truncated: the synthesis rate is chosen so
# that the whole sentence fits inside the target length.
# No personal recording is used or uploaded.
#
# Requirements: WSL with access to powershell.exe and the zh-CN SAPI voice.
# Output: samples/*.wav plus samples/manifest.txt
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ps="/mnt/c/Windows/System32/WindowsPowerShell/v1.0/powershell.exe"
mkdir -p "$here/raw" "$here/samples"

synth() { # text, outfile, rate
  local out_win
  out_win="$(wslpath -w "$2")"
  "$ps" -NoProfile -ExecutionPolicy Bypass -File "$(wslpath -w "$here/tools/gen-test-audio.ps1")" \
    -Text "$1" -OutFile "$out_win" -Rate "$3" >/dev/null
}

# 1 s: short utterance, low end of the length range. 0.91 s of speech.
synth "测试一" "$here/raw/1s.wav" 5
# 5 s: UPS term plus a point ID. 4.49 s of speech.
synth "测试内容，UPS 一号机输出电压二百二十伏，点位 P 零一是否告警。" "$here/raw/5s.wav" 5
# 15 s: upper bound of the board recording window. 14.26 s of speech.
synth "测试内容，当前 UPS 一号机运行正常，输出电压二百二十伏。点位 P 零一温度二十五点六度，点位 P 零二湿度百分之六十。请查询最近十分钟的告警记录。" "$here/raw/15s.wav" 2

python3 "$here/tools/pad_wav.py" "$here/raw/1s.wav"  "$here/samples/asr-1s-16k-mono.wav"  --seconds 1.0
python3 "$here/tools/pad_wav.py" "$here/raw/5s.wav"  "$here/samples/asr-5s-16k-mono.wav"  --seconds 5.0
python3 "$here/tools/pad_wav.py" "$here/raw/15s.wav" "$here/samples/asr-15s-16k-mono.wav" --seconds 15.0

# format tolerance checks derived from the same 5 s speech
python3 "$here/tools/pad_wav.py" "$here/raw/5s.wav" "$here/samples/asr-5s-8k-mono.wav"    --seconds 5.0 --rate 8000
python3 "$here/tools/pad_wav.py" "$here/raw/5s.wav" "$here/samples/asr-5s-44k1-stereo.wav" --seconds 5.0 --rate 44100 --channels 2

# digital silence: checks whether an empty transcript is returned
python3 - "$here/samples/asr-3s-silence.wav" <<'PY'
import sys, wave
path = sys.argv[1]
sr = 16000
with wave.open(path, "wb") as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr)
    w.writeframes(b"\x00\x00" * (sr * 3))
print(f"{path}: 1ch 16000Hz 16-bit 3.000s silence")
PY

{
  echo "# BVO-06 synthetic ASR samples"
  echo "# generated by tools/make-samples.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# file\tchannels\trate\tbits\tduration\tbytes\tsha256-16"
  for f in "$here"/samples/*.wav; do
    python3 - "$f" <<'PY'
import sys, wave, hashlib
p = sys.argv[1]
with wave.open(p, "rb") as w:
    ch, sr, sw, n = w.getnchannels(), w.getframerate(), w.getsampwidth(), w.getnframes()
raw = open(p, "rb").read()
print(f"{p.split('/')[-1]}\t{ch}ch\t{sr}Hz\t{sw*8}bit\t{n/sr:.3f}s\t{len(raw)}B\tsha256={hashlib.sha256(raw).hexdigest()[:16]}")
PY
  done
} > "$here/samples/manifest.txt"
rm -f "$here"/raw/t*.wav
cat "$here/samples/manifest.txt"
